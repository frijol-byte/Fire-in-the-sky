"""Blender asset builder (run with the bpy venv).

  tools/blender/.venv/bin/python tools/blender/build.py --recipe ships/test_kestrel
  tools/blender/.venv/bin/python tools/blender/build.py --all [--no-previews]

For each recipe: build the scene, validate names and budgets, export
game/assets/models/<category>/<id>.glb, write <id>.manifest.json next to it, and render the
contact sheet docs/previews/<id>.png. The manifest is the diffable record CI compares.
"""

import argparse
import importlib.util
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(HERE))

import bpy  # noqa: E402

import manifest as manifest_mod  # noqa: E402
from kit import common  # noqa: E402

RECIPES = HERE / "recipes"
MODELS = ROOT / "game" / "assets" / "models"
PREVIEWS = ROOT / "docs" / "previews"


def find_recipes() -> list[Path]:
    return sorted(p for p in RECIPES.rglob("*.py") if not p.name.startswith("_"))


def resolve_recipe(arg: str) -> Path:
    candidates = [
        Path(arg),
        RECIPES / arg,
        RECIPES / f"{arg}.py",
        HERE / arg,
        ROOT / arg,
        ROOT / f"{arg}.py",
    ]
    for c in candidates:
        if c.is_file():
            return c.resolve()
    raise SystemExit(f"recipe not found: {arg}")


def load_recipe(path: Path):
    spec = importlib.util.spec_from_file_location(f"recipe_{path.stem}", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    for attr in ("ID", "CATEGORY", "build"):
        if not hasattr(module, attr):
            raise SystemExit(f"{path}: recipe must define {attr}")
    return module


def export_glb(path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    bpy.ops.export_scene.gltf(
        filepath=str(path),
        export_format="GLB",
        export_yup=True,
        export_extras=True,
        export_apply=False,
        export_cameras=False,
        export_lights=False,
        export_image_format="NONE",
    )


def build_recipe(path: Path, previews: bool = True) -> dict:
    recipe = load_recipe(path)
    common.clear_scene()
    recipe.build()
    common.validate_names(bpy.data.objects)

    data = manifest_mod.collect(recipe)
    budget = getattr(recipe, "TRIANGLE_BUDGET", None)
    if budget and not budget[0] <= data["triangles"]["total"] <= budget[1]:
        raise SystemExit(
            f"{recipe.ID}: {data['triangles']['total']} triangles outside budget {budget}"
        )

    out_dir = MODELS / recipe.CATEGORY
    export_glb(out_dir / f"{recipe.ID}.glb")
    (out_dir / f"{recipe.ID}.manifest.json").write_text(
        json.dumps(data, indent=2, sort_keys=True) + "\n"
    )
    print(f"[build] {recipe.ID}: {data['triangles']['total']} tris -> {out_dir}")

    if previews:
        import previews as previews_mod

        title = f"{recipe.ID}   (placeholder, generated by tools/blender/build.py)"
        out = str(PREVIEWS / f"{recipe.ID}.png")
        if getattr(recipe, "PREVIEW", "ship") == "eye":
            previews_mod.render_eye_view(out, title, list(recipe.INFO))
        else:
            previews_mod.render_contact_sheet(out, title, manifest_mod.info_lines(data))
        print(f"[build] {recipe.ID}: preview -> docs/previews/{recipe.ID}.png")
    return data


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--recipe", action="append", default=[], help="recipe path or ships/<id>")
    ap.add_argument("--all", action="store_true", help="build every recipe")
    ap.add_argument("--no-previews", action="store_true", help="skip the Cycles renders")
    args = ap.parse_args(sys.argv[sys.argv.index("--") + 1 :] if "--" in sys.argv else None)
    if not args.recipe and not args.all:
        ap.error("pass --recipe <path> or --all")
    paths = find_recipes() if args.all else [resolve_recipe(r) for r in args.recipe]
    for p in paths:
        build_recipe(p, previews=not args.no_previews)


if __name__ == "__main__":
    main()
